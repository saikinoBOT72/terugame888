'use strict';
const COLS = 20;
/* =====================================================================
   パーツ（ステージの部品）
   1文字 = 1マス。上の行がパーツの上。横は必ず20文字。
     #  壁        .  空間       ^  トゲ（となりの壁から生える）
     /  \  45度の斜め（まわりの壁から向きを自動で決める）。上向きも下向きも張り付ける
     p q  出入りトゲ（q は p と半分ずれて出る）      >  <  扇風機（左の壁から右へ／右の壁から左へ吹く）
     XXXX 往復ブロックの通り道（横の並び）  Y 上下ブロックの通り道（縦の並び）  T 回る棒の軸  ==== シャッター（両端は壁）
   床も足場も、すべてマス単位のブロック（#）で作る
   つなぎ目のルール：
     - パーツのいちばん下の行といちばん上の行が「つなぎ口」。
       前のパーツの上のつなぎ口と、次のパーツの下のつなぎ口の形が同じものだけがつながる。
     - 上下それぞれ2行はトゲなし（どの高さで入ってきても立て直せるように）。
   ===================================================================== */
const PIECES = {};
function piece(id, opt, art) {
  let rows = art.split('\n').map(s => s.trimEnd()).filter(s => s.length);
  for (const r of rows) if (r.length !== COLS) throw new Error(`${id}: 行の長さが${r.length}文字（20文字にする）: "${r}"`);
  // G：ガチャ所の家を置くマス（すぐ下が床）。遊ぶときは空間
  let station = null;
  rows.forEach((r, i) => { const c = r.indexOf('G'); if (c >= 0) station = { c, r: rows.length - 1 - i }; });
  rows = rows.map(r => r.replace('G', '.'));
  PIECES[id] = { id, diff: opt.diff || 1, rows: rows.slice().reverse(), station, rain: !!opt.rain };   // rain：雨のパーツ（壁に掴まっていられる時間が1/4）   // 内部では下の行から（station.r も下から）
}
// ガチャ所：mirror で左右を入れ替えたもの（id_r）も作る
const mirror = art => art.split('\n').map(r => r.trimEnd().split('').reverse().join('').replace(/[\/\\]/g, ch => ch === '/' ? '\\' : '/')).join('\n');
function gachaPiece(id, art, both) { piece(id, {}, art); if (both) piece(id + '_r', {}, mirror(art)); }

